def parse_bool(value):
    normalized = str(value).strip().lower()
    if normalized in {"1", "true", "t", "yes", "y", "on"}:
        return True
    if normalized in {"0", "false", "f", "no", "n", "off", "release", ""}:
        return False
    raise ValueError(f"Invalid truth value: {value}")

